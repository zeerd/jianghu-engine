--   phase    "rank" | "respect" | "rude" | "self" | "self_rude" → a=对象, b=nil；
--            "close" | "self_close" → a=me, b=对方（可为 nil）；
--            "waimao" → a=性别字符串, b=容貌值（数值）。
--   返回值：称谓字符串（waimao 无匹配时返回空串）。
