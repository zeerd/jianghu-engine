--   调用点：setup_human 末尾（属性/气血/分支/体重之后）。
--   me  初始化中的人类角色（NPC 与玩家均会调用，脚本内自行区分）。
--   返回值：无（可 set/set_temp 补充初始化，如称号、内功加成）。
