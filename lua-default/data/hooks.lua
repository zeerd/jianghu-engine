-- hooks.can_prepare_combine(me, skill_a, skill_b, valid)
--   调用点：CCmdStandard::prepare 的组合判定（两处调用点）。
--   valid  既有 valid_combine 结果。
--   返回值：true = 可组合；false = 拒绝；
